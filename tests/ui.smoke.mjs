import {pdfFixture} from './fixtures.mjs';
import { migrate } from './migrate.mjs';
import {readFileSync,mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { Miniflare } from 'miniflare';
import { createHash,randomUUID } from 'node:crypto';
const mf=new Miniflare({modules:true,scriptPath:'dist/worker.mjs',compatibilityDate:'2026-07-30',d1Databases:{DB:'ui-smoke'},bindings:{PROVIDERS_JSON:'[]'}});
const db=await mf.getD1Database('DB');
await migrate(db);
const credentials={deviceId:randomUUID(),credential:'f'.repeat(64)},userId=randomUUID();
await db.prepare('INSERT INTO users(id) VALUES (?)').bind(userId).run();
await db.prepare('INSERT INTO devices VALUES (?,?,?,?,?,NULL)').bind(credentials.deviceId,userId,'Browser test',createHash('sha256').update(credentials.credential).digest('hex'),'owner').run();
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const origin=(await mf.ready).origin;
try{
await page.goto(origin+'/admin');
await page.locator('#login-form [name=deviceId]').fill(credentials.deviceId);
await page.locator('#login-form [name=credential]').fill(credentials.credential);
await page.locator('#login-form button').click();
await page.locator('#metrics .metric').first().waitFor();
assert.equal(await page.locator('#providers').innerText().then(s=>s.includes('Nenhum modelo conectado')),true);
await page.locator('[data-tab=memory]').click();
await page.locator('#memory-form [name=content]').fill('Registro de validação do painel CRONOS');
await page.locator('#memory-form [name=metadata]').fill('{"topics":["Validação","Painel"]}');
await page.locator('#memory-form button').click();
await page.getByText('Registro de validação do painel CRONOS',{exact:true}).waitFor();
await page.locator('[data-tab=graph]').click();
await page.locator('#graph-accessible summary').filter({hasText:'2 assuntos'}).waitFor();
await page.locator('#graph-search').fill('Painel');
await page.locator('#graph-canvas').hover();await page.mouse.wheel(0,-200);
mkdirSync('docs/screenshots',{recursive:true});
await page.screenshot({path:'docs/screenshots/graph.png',fullPage:true});
await page.locator('[data-tab=tools]').click();
await page.locator('#chart-form [name=points]').fill('[{"label":"Leitura","value":4},{"label":"Exercícios","value":7}]');
await page.locator('#chart-form button').click();await page.locator('#tool-result .bar').first().waitFor();
await page.locator('#media-form select').selectOption('document.pdf');
await page.locator('#media-form input[type=file]').setInputFiles({name:'test.pdf',mimeType:'application/pdf',buffer:Buffer.from(pdfFixture(),'base64')});
await page.locator('#media-form button').click();
await page.locator('#tool-result pre').filter({hasText:'CRONOS PDF real'}).waitFor();
await page.locator('[data-tab=agents]').click();await page.locator('#agent-list article').nth(39).waitFor();assert.equal(await page.locator('#agent-list article').count(),40);
await page.locator('[data-tab=overview]').click();await page.locator('#metrics .metric').first().waitFor();
await page.screenshot({path:'docs/screenshots/overview.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
await page.screenshot({path:'docs/screenshots/mobile.png',fullPage:true});
await page.locator('#logout').click();await page.locator('#login-form').waitFor();
assert.deepEqual(errors,[]);console.log('Browser checks passed: login, memory, graph, chart, PDF, 40 agents, responsive layout, logout; no JS exceptions.');
}finally{await browser.close();await mf.dispose();}
